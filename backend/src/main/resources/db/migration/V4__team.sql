-- V4: team assignment required for issuing scoped LiveKit team-room tickets.

CREATE TABLE team (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id  BIGINT       NOT NULL REFERENCES classroom (id),
    name          VARCHAR(255) NOT NULL,
    grade         SMALLINT,
    created_at    TIMESTAMP    NOT NULL,
    deleted_at    TIMESTAMP
);

CREATE INDEX idx_team_classroom ON team (classroom_id);

CREATE TABLE team_member (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id       BIGINT    NOT NULL REFERENCES team (id),
    classroom_id  BIGINT    NOT NULL REFERENCES classroom (id),
    user_id       BIGINT    NOT NULL REFERENCES users (id),
    joined_at     TIMESTAMP NOT NULL,

    CONSTRAINT uq_team_member_team_user UNIQUE (team_id, user_id),
    CONSTRAINT uq_team_member_classroom_user UNIQUE (classroom_id, user_id)
);

CREATE INDEX idx_team_member_team ON team_member (team_id);
