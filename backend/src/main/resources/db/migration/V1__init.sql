-- V1: 초기 스키마 — USER (ERD v1.0)
-- 규칙: 스키마 변경은 반드시 새 V{n}__*.sql 파일로. 이미 적용된 파일은 절대 수정 금지.

CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    VARCHAR(255) NOT NULL UNIQUE,
    password    VARCHAR(255) NOT NULL,
    name        VARCHAR(255) NOT NULL,
    role        VARCHAR(20)  NOT NULL,
    school      VARCHAR(255) NOT NULL,
    grade       SMALLINT,
    created_at  TIMESTAMP    NOT NULL,
    deleted_at  TIMESTAMP,

    -- 역할별 무결성: 학생만 grade 보유 (ERD 확정)
    CONSTRAINT users_role_grade_check CHECK (
        (role = 'STUDENT' AND grade IS NOT NULL) OR
        (role = 'TEACHER' AND grade IS NULL)
    )
);
