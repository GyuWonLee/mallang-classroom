-- V8: 학습자료 (ERD MATERIAL) — AI 과제 생성의 grounding 원천

CREATE TABLE material (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id      BIGINT       NOT NULL REFERENCES classroom (id),
    file_id           UUID         NOT NULL UNIQUE REFERENCES uploaded_file (id),
    title             VARCHAR(255) NOT NULL,
    -- 추출 결과 캐시 — 생성 시 매번 재추출하지 않기 위해
    extracted_text    TEXT,
    -- 2단계 추출 중 어느 쪽이 채웠는지: TEXT_LAYER | LLM (PREVIEW 안내·품질 판단용)
    extraction_source VARCHAR(20),
    -- PROCESSING → PREVIEW → READY / FAILED (PREVIEW 는 선생님 확인 대기)
    status            VARCHAR(20)  NOT NULL,
    -- FAILED 사유 (명세 §6.5: 실패 시 사유 반환)
    failure_reason    VARCHAR(255),
    created_at        TIMESTAMP    NOT NULL,
    deleted_at        TIMESTAMP
);

CREATE INDEX idx_material_classroom ON material (classroom_id);
