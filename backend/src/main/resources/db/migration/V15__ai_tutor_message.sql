-- V15: AI 말랑이(학생 튜터) 대화 기록 (명세 §11.1 #1).
--
-- 명세에 올라온 적 없던 기능이라 정책부터 정하고 들어간다. 기록을 남기는 이유는 두 가지다:
--   1) 안전 — 저학년이 쓰는 챗봇이라 무엇을 물었고 무엇을 답했는지 선생님이 확인할 수 있어야 한다
--   2) 비용 — 호출당 크레딧이 나가므로 누가 얼마나 썼는지 추적할 근거가 필요하다
--
-- 학급 종속인 이유: 열람 권한이 그 학급 선생님에게 있고, 학생이 학급을 떠나면 함께 정리된다.
-- 대화 '스레드'를 만들지 않는다 — 한 번의 질문·답이 완결된 단위이고, 문맥 이어붙이기는
-- 비용과 프롬프트 주입 위험을 함께 키운다.

CREATE TABLE ai_tutor_message (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id BIGINT    NOT NULL REFERENCES classroom (id),
    student_id   BIGINT    NOT NULL REFERENCES users (id),
    question     TEXT      NOT NULL,
    answer       TEXT      NOT NULL,
    answered_by  VARCHAR(20) NOT NULL,  -- LLM | TEMPLATE (키 없음·호출 실패 시 폴백)
    created_at   TIMESTAMP NOT NULL
);

CREATE INDEX idx_ai_tutor_message_student
    ON ai_tutor_message (classroom_id, student_id, created_at DESC);
