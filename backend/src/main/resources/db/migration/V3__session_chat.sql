-- V3: 수업/채팅 도메인 — LIVE_SESSION, SESSION_PARTICIPANT, CHAT_MESSAGE (ERD v1.2)

CREATE TABLE live_session (
                              id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              classroom_id  BIGINT    NOT NULL REFERENCES classroom (id),
                              started_by    BIGINT    NOT NULL REFERENCES users (id),
                              started_at    TIMESTAMP NOT NULL,
    -- NULL = 진행중 (별도 status 컬럼 없음)
                              ended_at      TIMESTAMP,
    -- 수업 종료 시 화이트보드 최종본 박제 (수업 중엔 Redis)
                              board_snapshot JSONB
);

-- 학급당 진행중 수업 1개 (동시 시작 → 409의 근거)
CREATE UNIQUE INDEX one_open_session_per_classroom
    ON live_session (classroom_id)
    WHERE ended_at IS NULL;

CREATE TABLE session_participant (
                                     id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     session_id  BIGINT    NOT NULL REFERENCES live_session (id),
                                     user_id     BIGINT    NOT NULL REFERENCES users (id),
                                     joined_at   TIMESTAMP NOT NULL,
    -- 재입장 시 새 행 (입퇴장 이력 그대로)
                                     left_at     TIMESTAMP
);

CREATE TABLE chat_message (
                              id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              session_id  BIGINT    NOT NULL REFERENCES live_session (id),
                              sender_id   BIGINT    NOT NULL REFERENCES users (id),
                              reply_to_id BIGINT REFERENCES chat_message (id),
                              content     TEXT      NOT NULL,
                              created_at  TIMESTAMP NOT NULL
);

CREATE INDEX idx_chat_message_session ON chat_message (session_id, created_at);