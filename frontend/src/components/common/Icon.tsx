const SLASHED = { micOff: 'mic', camOff: 'cam' } as const

export type IconName = keyof typeof ICON_PATHS | keyof typeof SLASHED | 'play' | 'grid'

interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'name'> {
  name: IconName
}

/**
 * 단색 SVG 아이콘. fill은 currentColor를 따르므로 text-* 유틸로 색을 제어한다.
 * play 아이콘만 (원 + 흰 삼각형) 특수 렌더.
 */
export function Icon({ name, className, ...props }: IconProps) {
  if (name === 'play') {
    return (
      <svg viewBox="0 0 24 24" className={className} aria-hidden="true" {...props}>
        <circle cx="12" cy="12" r="10" fill="currentColor" />
        <path
          d="M10 8.2v7.6a.7.7 0 0 0 1.1.6l5.6-3.8a.7.7 0 0 0 0-1.2l-5.6-3.8a.7.7 0 0 0-1.1.6Z"
          fill="var(--color-card)"
        />
      </svg>
    )
  }
  if (name === 'grid') {
    return (
      <svg viewBox="0 0 24 24" className={className} aria-hidden="true" {...props}>
        {[
          [3.6, 3.6],
          [13.2, 3.6],
          [3.6, 13.2],
          [13.2, 13.2],
        ].map(([x, y]) => (
          <rect key={`${x}-${y}`} x={x} y={y} width="7.2" height="7.2" rx="2.2" fill="currentColor" />
        ))}
      </svg>
    )
  }
  if (name in SLASHED) {
    return (
      <svg viewBox="0 0 24 24" className={className} aria-hidden="true" {...props}>
        <path d={ICON_PATHS[SLASHED[name as keyof typeof SLASHED]]} fill="currentColor" />
        <line
          x1="3.2"
          y1="3.2"
          x2="20.8"
          y2="20.8"
          stroke="currentColor"
          strokeWidth="2.6"
          strokeLinecap="round"
        />
      </svg>
    )
  }
  return (
    <svg viewBox="0 0 24 24" className={className} aria-hidden="true" {...props}>
      <path d={ICON_PATHS[name as keyof typeof ICON_PATHS]} fill="currentColor" />
    </svg>
  )
}
