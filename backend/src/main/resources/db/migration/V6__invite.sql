-- V6: 초대 (ERD INVITE) — 학급 입장은 초대 기반만 허용(공개 탐색 없음, 명세 §2·§3)

CREATE TABLE invite (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id  BIGINT      NOT NULL REFERENCES classroom (id),
    -- 혼동 문자(0/O, 1/I/L) 제외 문자셋 — 저학년이 옮겨 적는 경로
    code          VARCHAR(16) NOT NULL UNIQUE,
    type          VARCHAR(20) NOT NULL,
    created_by    BIGINT      NOT NULL REFERENCES users (id),
    expires_at    TIMESTAMP   NOT NULL,
    max_uses      INT         NOT NULL,
    -- 수락 트랜잭션에서 원자적 증가 (동시 가입에서도 max_uses 초과 방지)
    used_count    INT         NOT NULL DEFAULT 0,
    -- 즉시 만료. 유효 = expires_at > now AND revoked_at IS NULL AND used_count < max_uses
    revoked_at    TIMESTAMP,
    created_at    TIMESTAMP   NOT NULL
);

CREATE INDEX idx_invite_classroom ON invite (classroom_id);
