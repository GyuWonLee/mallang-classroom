-- V2: 학급 도메인 — CLASSROOM, CLASSROOM_MEMBER (ERD v1.1)

CREATE TABLE classroom (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    -- 학생 username 생성용 별칭. 서버가 단어 풀에서 자동 배정 (선생님 입력 없음)
    alias       VARCHAR(30)  NOT NULL UNIQUE,
    created_at  TIMESTAMP    NOT NULL,
    deleted_at  TIMESTAMP
);

CREATE TABLE classroom_member (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id  BIGINT      NOT NULL REFERENCES classroom (id),
    user_id       BIGINT      NOT NULL REFERENCES users (id),
    -- 학급 내 권한 (USER.role과 별개): OWNER | MAINTAINER | STUDENT
    role          VARCHAR(20) NOT NULL,
    joined_at     TIMESTAMP   NOT NULL,
    -- 강퇴 = soft delete. 재가입은 기존 행 재활성화 (UNIQUE 제약 때문)
    deleted_at    TIMESTAMP,

    CONSTRAINT uq_classroom_member UNIQUE (classroom_id, user_id)
);

-- OWNER는 학급당 1명 (살아있는 행 기준) — ERD 확정
CREATE UNIQUE INDEX one_owner_per_classroom
    ON classroom_member (classroom_id)
    WHERE role = 'OWNER' AND deleted_at IS NULL;
