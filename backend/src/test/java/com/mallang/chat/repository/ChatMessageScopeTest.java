package com.mallang.chat.repository;

import com.mallang.chat.entity.ChatMessage;
import com.mallang.classroom.entity.Classroom;
import com.mallang.global.config.JpaConfig;
import com.mallang.session.entity.LiveSession;
import com.mallang.user.entity.User;
import jakarta.persistence.EntityManager;
import jakarta.persistence.PersistenceContext;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.data.jpa.test.autoconfigure.DataJpaTest;
import org.springframework.context.annotation.Import;
import org.springframework.test.context.TestPropertySource;

import java.time.LocalDateTime;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * 한 표에 사는 두 계통(수업 채팅 / 쪽지)이 서로의 조회에 새어 들지 않는지.
 *
 * <p>목으로는 잡히지 않는 종류의 결함이다. 리포지토리를 목으로 두면 JPQL 의 조건이 사라져
 * 무엇을 거르고 무엇을 안 거르는지가 검증 대상에서 통째로 빠진다.
 *
 * <p>특히 위험한 지점: 예전에는 수업 채팅이 recipient 를 안 써서 {@code recipient is not null}
 * 만으로 쪽지가 걸러졌다. 선생님 메시지에 수신자를 적기 시작하면 그 우연이 깨지므로,
 * 계통을 가르는 조건이 {@code session} 으로 옮겨 갔는지를 여기서 붙들어 둔다.
 */
@DataJpaTest
@Import(JpaConfig.class)
@TestPropertySource(properties = {
        "spring.jpa.hibernate.ddl-auto=create-drop",
        "spring.flyway.enabled=false"
})
class ChatMessageScopeTest {

    @PersistenceContext
    EntityManager em;

    @Autowired
    ChatMessageRepository chatMessageRepository;

    private Classroom classroom;
    private LiveSession session;
    private User teacher;
    private User student;

    /**
     * {@code live_session.board_snapshot} 은 Postgres 전용 {@code jsonb} 라 H2 가 그 표를
     * 못 만든다(테스트 프로필이 H2 를 쓰는 이유는 application.yml 주석 참고). 이 테스트가
     * 보려는 것은 스냅샷이 아니라 <b>채팅 쿼리의 범위</b>이므로, 그 컬럼만 CLOB 으로 바꿔
     * 표를 직접 만든다.
     */
    @BeforeEach
    void setUp() {
        createSessionTableH2CannotBuild();
        teacher = teacher("t" + System.nanoTime() + "@school.kr");
        student = student("dodam" + System.nanoTime());
        classroom = Classroom.create("3학년 2반", "dodam" + System.nanoTime(), List.of((short) 3));
        em.persist(classroom);
        session = LiveSession.start(classroom, teacher);
        em.persist(session);
        em.flush();
    }

    private void createSessionTableH2CannotBuild() {
        em.createNativeQuery("CREATE TABLE IF NOT EXISTS live_session ("
                + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                + "classroom_id BIGINT NOT NULL,"
                + "started_by BIGINT NOT NULL,"
                + "started_at TIMESTAMP NOT NULL,"
                + "ended_at TIMESTAMP,"
                // 학년별 수업(V31). 이 표는 손으로 만들므로 엔티티에 열이 늘면 여기도 늘려야 한다
                + "grade SMALLINT,"
                + "board_snapshot CLOB)").executeUpdate();
    }

    // ── 답장이 아닌 교사 메시지가 사라지던 문제 ────────────────────────────────

    @Test
    @DisplayName("답장 형식이 아닌 교사 메시지도 학생 스레드에 들어온다")
    void aTeacherMessageThatIsNotAReplyStillBelongsToTheStudentThread() {
        save(ChatMessage.of(session, student, "받침이 뭐예요?", null));
        // replyTo 없이 보낸 교사 메시지 — 발행부가 replyToId 를 선택 인자로 두고 있어 실제로 생긴다
        save(ChatMessage.of(session, teacher, student, "글자 아래 자음이야!", null));
        em.clear();

        assertThat(chatMessageRepository.findThread(session.getId(), student.getId()))
                .extracting(ChatMessage::getContent)
                .containsExactly("받침이 뭐예요?", "글자 아래 자음이야!");
    }

    @Test
    @DisplayName("학생의 /me/messages 에도 그 메시지가 남는다 — 새로고침해도 사라지지 않는다")
    void theStudentStillSeesItAfterAReload() {
        save(ChatMessage.of(session, teacher, student, "오늘 발표 잘했어!", null));
        em.clear();

        assertThat(chatMessageRepository.findAllInvolving(student.getId()))
                .extracting(ChatMessage::getContent)
                .containsExactly("오늘 발표 잘했어!");
    }

    // ── 계통이 섞이지 않는지 ──────────────────────────────────────────────────

    @Test
    @DisplayName("내가 보낸 쪽지는 /me/messages 에 딸려 나오지 않는다 — 쪽지 API 와 겹쳐 두 번 그려졌다")
    void myDirectMessagesDoNotLeakIntoTheSessionChatHistory() {
        save(ChatMessage.direct(classroom, student, teacher, "선생님 안녕하세요"));
        save(ChatMessage.of(session, student, "수업 중 질문이에요", null));
        em.clear();

        assertThat(chatMessageRepository.findAllInvolving(student.getId()))
                .extracting(ChatMessage::getContent)
                .containsExactly("수업 중 질문이에요");
    }

    @Test
    @DisplayName("교사의 수업 채팅은 쪽지 대화에 섞이지 않는다")
    void sessionChatDoesNotLeakIntoTheDirectConversation() {
        save(ChatMessage.of(session, teacher, student, "수업 중에 보낸 말", null));
        save(ChatMessage.direct(classroom, teacher, student, "쪽지로 보낸 말"));
        em.clear();

        assertThat(chatMessageRepository
                .findConversation(classroom.getId(), student.getId(), teacher.getId()))
                .extracting(ChatMessage::getContent)
                .containsExactly("쪽지로 보낸 말");
    }

    @Test
    @DisplayName("교사의 수업 채팅은 쪽지 목록에도 섞이지 않는다")
    void sessionChatDoesNotLeakIntoTheDirectThreadList() {
        save(ChatMessage.of(session, teacher, student, "수업 중에 보낸 말", null));
        em.clear();

        assertThat(chatMessageRepository.findMyDirectMessages(student.getId())).isEmpty();
    }

    @Test
    @DisplayName("쪽지 읽음 처리가 수업 채팅까지 읽음으로 찍지 않는다")
    void markingADirectThreadReadDoesNotTouchSessionChat() {
        ChatMessage inSession = save(ChatMessage.of(session, teacher, student, "수업 중에 보낸 말", null));
        ChatMessage asDirect = save(ChatMessage.direct(classroom, teacher, student, "쪽지로 보낸 말"));
        em.clear();

        int marked = chatMessageRepository.markThreadRead(
                classroom.getId(), teacher.getId(), student.getId(), LocalDateTime.now());
        em.clear();

        assertThat(marked).isEqualTo(1);
        assertThat(chatMessageRepository.findById(asDirect.getId()).orElseThrow().getReadAt())
                .isNotNull();
        assertThat(chatMessageRepository.findById(inSession.getId()).orElseThrow().getReadAt())
                .describedAs("읽음은 쪽지에서만 의미가 있는 값이다")
                .isNull();
    }

    // ── 기존 동작이 그대로인지 ────────────────────────────────────────────────

    @Test
    @DisplayName("답장은 예전처럼 원본 학생의 스레드에 붙는다")
    void repliesStillAttachToTheOriginalStudentThread() {
        ChatMessage question = save(ChatMessage.of(session, student, "이거 어떻게 해요?", null));
        save(ChatMessage.of(session, teacher, student, "이렇게 해 보자", question));
        em.clear();

        assertThat(chatMessageRepository.findThread(session.getId(), student.getId())).hasSize(2);
    }

    @Test
    @DisplayName("다른 학생의 대화는 내 스레드에 들어오지 않는다")
    void anotherStudentsConversationStaysOut() {
        User other = student("other" + System.nanoTime());
        save(ChatMessage.of(session, other, "저도 질문 있어요", null));
        save(ChatMessage.of(session, teacher, other, "그래 말해 보렴", null));
        save(ChatMessage.of(session, student, "제 질문이에요", null));
        em.clear();

        assertThat(chatMessageRepository.findThread(session.getId(), student.getId()))
                .extracting(ChatMessage::getContent)
                .containsExactly("제 질문이에요");
        assertThat(chatMessageRepository.findAllInvolving(student.getId()))
                .extracting(ChatMessage::getContent)
                .containsExactly("제 질문이에요");
    }

    // ── 픽스처 ────────────────────────────────────────────────────────────────

    private ChatMessage save(ChatMessage message) {
        em.persist(message);
        em.flush();
        return message;
    }

    private User teacher(String email) {
        User user = User.createTeacher(email, "encoded", "이선생", "싸피초등학교");
        em.persist(user);
        return user;
    }

    private User student(String username) {
        User user = User.createStudent(username, "encoded", "김민수", "싸피초등학교", (short) 3);
        em.persist(user);
        return user;
    }
}
