-- 선생님이 학생별로 과목·영역별 평가(평가요소 문장 + 평가 등급)를 담아 저장한다.
-- 표 구조가 유형처럼 유연해 유형별 스키마 분리 대신 content(jsonb) 한 컬럼에 담는다
-- (assignment.content 와 같은 ERD 원칙): {"entries":[{subject,area,evalElement,rating}]}.
--
-- 학생당 학급별 한 장만 둔다. 학생이 학급을 떠나면 함께 정리된다(학급 종속).

CREATE TABLE report_card (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id BIGINT    NOT NULL REFERENCES classroom (id),
    student_id   BIGINT    NOT NULL REFERENCES users (id),
    content      JSONB     NOT NULL,
    updated_at   TIMESTAMP NOT NULL,
    CONSTRAINT uq_report_card UNIQUE (classroom_id, student_id)
);
