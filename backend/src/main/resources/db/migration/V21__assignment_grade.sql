-- V21: 과제에 학년(grade) 저장.
--
-- 그동안 학년은 AI 생성 프롬프트의 난이도 참고용으로만 쓰고 버렸다(과목 subject 은 저장하면서 학년은 안 했다).
-- 그러다 보니 저장된 과제에서 학년을 알 수 없어 화면이 "1학년 국어"처럼 표시하지 못했다.
-- 이제 생성 시 넘어온 학년을 과제에 함께 저장한다.
--
-- nullable 인 이유: 직접 작성 과제는 학년 없이 만들 수 있고, 기존 행에도 값이 없다. 1~6 범위는
-- 요청 DTO(@Min/@Max)에서 검증한다.

ALTER TABLE assignment ADD COLUMN grade INTEGER;
