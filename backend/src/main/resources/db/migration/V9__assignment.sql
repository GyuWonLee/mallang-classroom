-- V9: 과제(Assignment) — 직접 작성 + AI 생성 확정 저장 대상.
-- (원래 V6 였으나 invite 의 V6 와 번호가 겹쳐 배포가 깨져 V9 으로 옮겼다.
--  invite/uploaded_file 은 이미 운영에 적용된 버전이라 그쪽은 건드릴 수 없다.)
-- 진행 중 AI 생성 초안(genjob)은 Redis(genjob:{jobId})에만 존재하고, 확정 시에만 이 테이블에 행 생성.
-- enum은 VARCHAR + @Enumerated(STRING) (ERD 설계 원칙). content/source_material_ids는 JSONB.

CREATE TABLE assignment (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id        BIGINT       NOT NULL REFERENCES classroom (id),
    created_by          BIGINT       NOT NULL REFERENCES users (id),
    title               VARCHAR(255) NOT NULL,
    subject             VARCHAR(30)  NOT NULL,  -- KOREAN | HANJA
    type                VARCHAR(30)  NOT NULL,  -- DICTATION | MULTIPLE_CHOICE | PARTICLE_CHOICE | OX | QUIZ_GAME
    source              VARCHAR(20)  NOT NULL,  -- MANUAL | AI_GENERATED (AI 활용 통계·뱃지용)
    content             JSONB        NOT NULL,  -- type별 문제 스키마 (문항 공통: conceptTags·level·sourceRef)
    source_material_ids JSONB,                  -- 근거 학습자료 ID 배열 (MANUAL은 NULL)
    due_at              TIMESTAMP,
    published_at        TIMESTAMP,              -- NULL = 초안(학생에게 안 보임). AI 초안 확정 = 이 값 기록
    created_at          TIMESTAMP    NOT NULL,
    deleted_at          TIMESTAMP
);

-- 학급별 과제 목록 조회 (살아있는 행 기준)
CREATE INDEX idx_assignment_classroom ON assignment (classroom_id) WHERE deleted_at IS NULL;
