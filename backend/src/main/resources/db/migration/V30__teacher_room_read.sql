-- V30: 교사 단톡방 읽음 표시.
--
-- 단톡방 메시지 자체는 chat_message 를 그대로 쓴다 — session 도 recipient 도 없는 행이
-- 단톡방이다(수업 채팅은 session, 1:1 은 recipient 가 있다). 세 계통이 한 표에 살지만
-- 조회 쿼리가 서로를 배제하고 있어 섞이지 않는다.
--
-- 읽음만 따로 둔다. 1:1 은 chat_message.read_at 하나로 됐다 — 받는 사람이 한 명이라
-- 행과 독자가 1:1 이었다. 단톡방은 한 메시지를 여럿이 읽으므로 그 칸에 담을 수 없다.
-- 대신 사람마다 '마지막으로 읽은 시각' 하나만 들고, 그보다 뒤에 온 메시지를 안 읽음으로 센다.
-- 메시지가 늘어도 행이 늘지 않아 방이 길어져도 비용이 일정하다.
--
-- 행이 없으면 '한 번도 읽지 않음'이다. 새로 초대된 선생님에게 그동안의 대화가 전부
-- 안 읽음으로 보이는 편이 자연스러워서, 초대 시점에 행을 만들지 않는다.
CREATE TABLE teacher_room_read (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id BIGINT      NOT NULL REFERENCES classroom (id),
    user_id      BIGINT      NOT NULL REFERENCES users (id),
    last_read_at TIMESTAMP   NOT NULL,
    CONSTRAINT uk_teacher_room_read_classroom_user UNIQUE (classroom_id, user_id)
);

-- 안 읽은 개수를 셀 때 (학급, 사람)으로 한 행을 집는다 — 유니크 제약이 그 인덱스를 겸한다.
-- 방 조회는 chat_message 쪽 (classroom_id, created_at) 을 타므로 여기서 더 만들 것이 없다.
