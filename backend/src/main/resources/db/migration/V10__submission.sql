-- V10: 과제 제출 + 즉시 자동채점 (ERD SUBMISSION). 재제출은 새 행으로 모든 시도 보존.
-- 학습이력/이해도는 별도 테이블 없이 이 행의 score/results/ai_analysis 집계로 도출 (ERD 원칙).

CREATE TABLE submission (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT    NOT NULL REFERENCES assignment (id),
    student_id    BIGINT    NOT NULL REFERENCES users (id),
    answers       JSONB     NOT NULL,   -- 문항번호 → 답
    score         SMALLINT,             -- 자동 채점 점수(0~100). 수동 채점 유형은 NULL
    results       JSONB     NOT NULL,   -- 문항별 정오 [{no, correct, conceptTags}]
    ai_analysis   JSONB,                -- LLM 해석 캐시 (errorPattern·comment — 숫자 금지)
    attempt_no    INT       NOT NULL,   -- 학생별 제출 시도 번호 (1부터)
    submitted_at  TIMESTAMP NOT NULL,

    CONSTRAINT uq_submission UNIQUE (assignment_id, student_id, attempt_no)
);

CREATE INDEX idx_submission_assignment ON submission (assignment_id);
CREATE INDEX idx_submission_student ON submission (student_id);
