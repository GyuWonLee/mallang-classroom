-- 본인이 보면 안 되고(권한은 애플리케이션에서 관리자 전용으로 막는다), 학급을 옮기면
-- 따라가지 않는다 — 그래서 학급 종속(classroom_id)이다.

CREATE TABLE student_note (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id BIGINT    NOT NULL REFERENCES classroom (id),
    student_id   BIGINT    NOT NULL REFERENCES users (id),
    author_id    BIGINT    NOT NULL REFERENCES users (id),  -- 남긴 선생님. 수정·삭제는 이 사람만
    content      TEXT      NOT NULL,
    created_at   TIMESTAMP NOT NULL,
    updated_at   TIMESTAMP NOT NULL
);

-- 조회는 항상 "이 학급의 이 학생" 단위이고 최근 것이 위로 온다
CREATE INDEX idx_student_note_target
    ON student_note (classroom_id, student_id, created_at DESC);
