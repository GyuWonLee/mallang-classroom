-- V32: 학급당 진행중 수업 1개를 강제하던 V3 의 옛 인덱스를 걷어낸다.
--
-- V31 이 학년별 수업을 도입하며 (classroom_id, grade) 유니크 인덱스를 새로 만들었는데,
-- V3 의 one_open_session_per_classroom (classroom_id 단독) 은 그대로 남아 있었다.
-- 새 인덱스를 "추가"만 하고 옛 전제를 지우지 않은 것이다. 그래서 V31 의 목적인
-- "학년별로 따로 도는 수업"이 DB 에서 통째로 막혀 있었다.
--
-- 증상은 화면 끝까지 이어졌다. 1학년 수업이 열린 학급에서 5학년 수업을 시작하면
--   1) SessionService.start 의 학년 검사는 통과한다 (1 != 5)
--   2) insert 가 옛 인덱스의 유니크 위반으로 튕긴다
--   3) 그래서 session-already-open(409) 이 아니라 전역 conflict(409) 가 나간다
--   4) 화면은 그 409 를 "이 학년 수업이 이미 열렸다"로 읽고 다시 조회하는데, 5학년 수업도
--      학급 전체 수업도 없으니 아무것도 못 찾고 엉뚱한 안내를 띄웠다
-- 두 선생님이 한 학급에서 학년을 나눠 수업할 수 없었다는 뜻이다.
--
-- ux_live_session_open_per_grade 가 같은 자리를 이미 지키고 있다 — 진행 중인 수업은
-- (학급, 학년) 당 하나이고, 학년 없는 수업(= 학급 전체)은 nulls not distinct 로 하나만
-- 열린다. 동시 요청 경합에 대한 마지막 방어선은 그대로 남는다.
drop index if exists one_open_session_per_classroom;
