-- V17: 학급 alias 의 유일성 요구를 걷어낸다.
--
-- 배경: V16 에서 유니크 범위를 '살아있는 학급'으로 좁혀 급한 500 은 막았지만,
-- "살아있는 학급마다 전역에서 유일한 단어를 하나씩 점유한다"는 구조는 그대로였다.
-- 단어 풀이 유한하므로 학급이 늘면 같은 문제가 다시 온다 (풀을 늘려도 시점만 미뤄진다).
--
-- 판단: alias 의 유일성은 애초에 필요한 제약이 아니었다. 실제로 지켜야 하는 것은
-- users.username 의 유일성이고, 그것은 StudentAccountIssuer.nextStudentUsername() 의
-- do/while 이 existsByUsernameIncludingDeleted() 로 이미 보장한다. 두 학급이 같은
-- alias 를 써도 한쪽이 dodam01~05, 다른 쪽이 dodam06~10 을 받아 충돌하지 않는다.
--
-- 결과: 단어 풀 크기가 학급 수의 상한이 아니게 된다. AliasGenerator 는 DB 를 조회하지
-- 않고 무작위로 한 단어를 고르며, 소진 시 폴백(dodam-2)도 필요 없어진다.
--
-- 대가: 살아있는 학급 둘이 같은 alias 를 가질 수 있고, 그 경우 한 학급의 학생 번호가
-- 01 부터 연속이 아닐 수 있다 (username 자체는 여전히 유일하다).
--
-- 블루-그린 안전성: 제약을 제거하는 방향이라 전환 중 함께 도는 구버전도 그대로 동작한다.
-- 구버전의 existsByAlias() 는 중복을 피하려 들 뿐이므로 오동작하지 않는다.

DROP INDEX IF EXISTS uq_classroom_alias_live;
