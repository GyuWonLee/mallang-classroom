/**
 * '오늘의 활동' 목록 칸의 **고정 높이**(px) — 두 탭 중 **더 높은 쪽**(활동) 5줄이 들어가는 크기다.
 *
 * 왜 고정인가: 예전엔 목록이 내용만큼 늘고 `.slice(0, 5)` 로 나머지를 **말없이 잘라 냈다.**
 * 과제가 1개인 학급과 5개인 학급에서 카드 높이가 달랐고, 6번째부터는 있는 줄도 몰랐다.
 * 이제 높이를 못박고 넘치는 만큼은 페이지로 넘긴다.
 *
 * 값의 근거(브라우저 실측, 칸 너비 520px 기준 — 실제는 더 넓어 줄바꿈이 덜하다):
 *  - 과제 줄 5개 = 264px  (`py-3.5` + 알약 한 줄)
 *  - 활동 줄 5개 = 284px, 제목이 두 줄로 넘칠 때 289px
 *    (`py-3` 인데도 더 높다 — 제목 아래 `actorName` 줄이 하나 더 붙는다)
 *  → **활동 쪽에 맞춘다: 290**
 *
 * 예전 값은 269 로 **과제 쪽에만** 맞춰져 있었다. 그래서 활동 탭은 5줄이 20px 넘쳐 늘
 * 스크롤바가 떴다 — 페이지 넘김이 이미 있는 칸에 스크롤까지 생기면 "끝까지 봤는지"가
 * 두 갈래로 갈린다. 두 탭 모두 스크롤을 없애는 대신 높이를 더 높은 쪽에 맞췄다
 * (과제 탭 아래가 26px 남는 건 감수한다 — 탭을 오갈 때 카드가 튀지 않는 게 더 중요하다).
 *
 * ※ 줄 높이는 글자 줄 높이에 딸려 간다. `index.css` 의 기본 `line-height` 를 건드리면
 *   이 값도 같이 다시 재야 한다.
 */
export const TODAY_LIST_H = 290

