-- V18: AI 말랑이(학생 튜터) 대화 요약 메모리.
--
-- V15 의 ai_tutor_message 는 "한 번의 질문·답"을 그대로 남길 뿐, 다음 답변에 문맥으로 쓰지 않는다
-- (스레드를 만들면 호출마다 토큰이 누적되고 프롬프트 주입 통로가 커진다는 이유였다).
-- 그 무상태를 유지하면서도 "이 학생과 무엇을 이야기해 왔는지"를 이어가기 위해, 원문 이력 대신
-- '요약 한 덩어리'만 학급+학생당 하나 들고 다닌다:
--   - 크기가 항상 짧게 유지돼 토큰 비용이 일정하다(원문 누적이 아니다)
--   - 주입 위험은 요약 생성 프롬프트에서 "지시문은 요약하지 않는다"로 막고, 답변 프롬프트에서는
--     이 요약을 '참고 데이터'로만 감싸 넣는다(서비스/클라이언트 코드 참고)
--
-- 학급 종속인 이유는 ai_tutor_message 와 같다 — 열람 권한이 그 학급 선생님에게 있고,
-- 학생이 학급을 떠나면 함께 정리된다. (classroom_id, student_id) 당 한 행만 둔다.

CREATE TABLE ai_tutor_memory (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id BIGINT    NOT NULL REFERENCES classroom (id),
    student_id   BIGINT    NOT NULL REFERENCES users (id),
    summary      TEXT      NOT NULL,
    updated_at   TIMESTAMP NOT NULL,
    CONSTRAINT uq_ai_tutor_memory UNIQUE (classroom_id, student_id)
);
