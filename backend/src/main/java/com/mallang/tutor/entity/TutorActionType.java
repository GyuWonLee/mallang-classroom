package com.mallang.tutor.entity;

/**
 * 말랑이가 제안할 수 있는 액션.
 *
 * <p>둘로 시작한다. 되돌리기 어려운 동작(수정·삭제)은 넣지 않는다 — 사용자가 초등학생이라
 * 원탭 오조작의 대가가 크다.</p>
 */
public enum TutorActionType {

    /**
     * 선생님에게 질문을 보낸다. 착지점이 둘이라 서버가 고른다 —
     * 수업 중이면 수업 채팅 라우팅, 아니면 학급 선생님에게 쪽지.
     * 아이에게 어느 쪽으로 보낼지 묻지 않는다(고를 이유가 없는 선택지다).
     */
    ASK_TEACHER,

    /**
     * 학습자료를 열어 준다. 말랑이가 답을 지어내는 대신 "자료 어디를 봐"로 보내는 쪽이
     * 초등 학습에 맞고, 과제 생성이 근거 인용을 강제하는 것과 같은 방향이다.
     */
    SHOW_MATERIAL
}
